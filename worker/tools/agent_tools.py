def tool_generate_notebook(work_dir: Path, filename: str, cells: List[Dict[str, str]]) -> str:
    """
    Creates a valid Jupyter notebook from a list of cell specs.
    Each cell spec: {"type": "code"|"markdown", "content": "..."}
    Saves to work_dir/filename. Returns success or error.
    Zero external dependencies (pure standard library json).
    """
    try:
        nb_cells = []
        for cell in cells:
            cell_type = cell.get("type", "code")
            content = cell.get("content", "")
            if cell_type == "markdown":
                nb_cells.append({
                    "cell_type": "markdown",
                    "metadata": {},
                    "source": [content] if isinstance(content, str) else content,
                })
            else:
                nb_cells.append({
                    "cell_type": "code",
                    "execution_count": None,
                    "metadata": {},
                    "outputs": [],
                    "source": [content] if isinstance(content, str) else content,
                })

        nb_dict = {
            "cells": nb_cells,
            "metadata": {
                "kernelspec": {
                    "display_name": "Python 3",
                    "language": "python",
                    "name": "python3",
                },
                "language_info": {
                    "name": "python",
                    "version": "3.12.0",
                },
            },
            "nbformat": 4,
            "nbformat_minor": 5,
        }
        target = work_dir / filename
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(json.dumps(nb_dict, indent=2), encoding="utf-8")
        size = target.stat().st_size
        return _ok(f"Notebook '{filename}' written ({len(nb_cells)} cells, {size:,} bytes)")
    except Exception as e:
        return _err(str(e))


