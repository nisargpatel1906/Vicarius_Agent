def tool_package_zip(work_dir: Path, archive_name: str, include_files: Optional[List[str]] = None, wrap_in_folder: Optional[bool] = None) -> str:
    """
    Package files in the workspace into a ZIP archive.
    If include_files is specified, only those files are included.
    Otherwise, all workspace files (excluding build caches) are included.
    Automatically wraps files inside an inner folder matching the archive stem
    (e.g. DLCV_2025_STUDENT_ID_sub1/file.ext) to comply with academic submission standards.
    """
    import zipfile as zf

    JUNK = {"node_modules", ".venv", "venv", "__pycache__", ".git", ".next", "dist", "build"}

    try:
        archive_path = work_dir / archive_name
        files_to_zip: List[Path] = []

        if include_files:
            for fname in include_files:
                p = (work_dir / fname).resolve()
                if p.exists() and str(p).startswith(str(work_dir.resolve())):
                    files_to_zip.append(p)
                else:
                    # Try glob
                    found = list(work_dir.glob(fname))
                    files_to_zip.extend(found)
        else:
            for root, dirs, files in os.walk(work_dir):
                dirs[:] = [d for d in dirs if d not in JUNK and not d.startswith(".")]
                for f in files:
                    p = Path(root) / f
                    if (
                        p.name.startswith(".")
                        or p.suffix in {".log", ".pyc"}
                        or p.name == archive_name
                        or "project.zip" in p.name
                    ):
                        continue
                    files_to_zip.append(p)

        if not files_to_zip:
            return _err("No files found to package.")

        stem = Path(archive_name).stem
        should_wrap = wrap_in_folder if wrap_in_folder is not None else True

        with zf.ZipFile(archive_path, "w", zf.ZIP_DEFLATED) as z:
            for f in files_to_zip:
                try:
                    rel_name = f.relative_to(work_dir)
                except ValueError:
                    rel_name = Path(f.name)
                rel_str = str(rel_name).replace("\\", "/")
                if should_wrap and not rel_str.startswith(f"{stem}/"):
                    arcname = f"{stem}/{rel_str}"
                else:
                    arcname = rel_str
                z.write(f, arcname=arcname)

        size = archive_path.stat().st_size
        names = ", ".join(f.name for f in files_to_zip[:8])
        if len(files_to_zip) > 8:
            names += f", ... ({len(files_to_zip)} total)"
        wrap_note = f", wrapped in '{stem}/'" if should_wrap else ""
        return _ok(f"Archive '{archive_name}' created ({size:,} bytes{wrap_note}). Contains: {names}")
    except Exception as e:
        return _err(str(e))


