def tool_execute_notebook(work_dir: Path, filename: str, timeout: int = 600) -> str:
    """
    Execute a Jupyter notebook (.ipynb) headlessly in the work directory using nbclient.
    Runs all code cells in sequence, captures their output (including charts and stdout),
    and saves the executed notebook back in-place.
    """
    try:
        target = (work_dir / filename).resolve()
        if not str(target).startswith(str(work_dir.resolve())):
            return _err(f"Path '{filename}' escapes work_dir.")
        if not target.exists():
            return _err(f"Notebook file '{filename}' does not exist.")

        import nbformat
        from nbclient import NotebookClient

        nb = nbformat.read(str(target), as_version=4)
        client = NotebookClient(
            nb,
            timeout=timeout,
            kernel_name="python3",
            resources={"metadata": {"path": str(work_dir)}},
        )
        client.execute()
        with open(str(target), "w", encoding="utf-8") as f:
            nbformat.write(nb, f)

        executed_cells = sum(1 for c in nb.cells if c.get("cell_type") == "code" and len(c.get("outputs", [])) > 0)
        size = target.stat().st_size
        return _ok(f"Notebook '{filename}' successfully executed ({executed_cells} code cells with outputs, {size:,} bytes).")
    except Exception as e:
        return _err(f"Notebook execution failed: {e}")


