def _detect_python_exe() -> str:
    if os.getenv("AGENT_PYTHON_EXE") and Path(os.environ["AGENT_PYTHON_EXE"]).exists():
        return os.environ["AGENT_PYTHON_EXE"]
    # 1. Prefer Python 3.12 (standard student ML & CUDA environment)
    py312 = Path(r"python.exe")
    if py312.exists():
        return str(py312)
    # 2. Check local workspace .venv
    local_venv = Path(__file__).resolve().parent.parent.parent / ".venv" / "Scripts" / "python.exe"
    if local_venv.exists():
        return str(local_venv)
    # 3. Check current runtime python
    if sys.executable and Path(sys.executable).exists():
        return sys.executable
    # 4. Fallback
    return r"python.exe"

PYTHON_EXE = _detect_python_exe()


def tool_run_python(work_dir: Path, code: str, timeout: int = 60) -> str:
    """
    Execute Python code in a subprocess within work_dir.
    Returns stdout + stderr (capped at 3000 chars).
    This gives the agent real feedback on whether its code actually works.
    """
    try:
        result = subprocess.run(
            [PYTHON_EXE, "-c", code],
            capture_output=True,
            text=True,
            timeout=timeout,
            cwd=str(work_dir),
            env={**os.environ, "PYTHONPATH": str(work_dir)},
        )
        out = result.stdout.strip()
        err = result.stderr.strip()
        combined = ""
        if out:
            combined += f"STDOUT:\n{out}"
        if err:
            combined += f"\nSTDERR:\n{err}"
        if not combined:
            combined = "(no output)"
        if result.returncode != 0:
            combined = f"[EXIT CODE {result.returncode}]\n" + combined
        # Truncate
        if len(combined) > 3000:
            combined = combined[:3000] + "\n... [output truncated]"
        return combined
    except subprocess.TimeoutExpired:
        return _err(f"Code execution timed out after {timeout}s.")
    except Exception as e:
        return _err(str(e))


