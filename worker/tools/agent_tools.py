def tool_read_file(work_dir: Path, path: str, max_chars: int = 4000) -> str:
    """Read a file and return its content (capped at max_chars)."""
    try:
        target = (work_dir / path).resolve()
        if not str(target).startswith(str(work_dir.resolve())):
            return _err(f"Path '{path}' escapes work_dir.")
        if not target.exists():
            return _err(f"File '{path}' does not exist.")
        raw = target.read_text(encoding="utf-8", errors="replace")
        if len(raw) > max_chars:
            raw = raw[:max_chars] + f"\n... [truncated — full file is {target.stat().st_size:,} bytes]"
        return raw
    except Exception as e:
        return _err(str(e))


