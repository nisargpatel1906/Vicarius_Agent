# ─────────────────────────────────────────────

def tool_write_file(work_dir: Path, path: str, content: str) -> str:
    """
    Write content to a file inside work_dir.
    - For .ipynb: validates JSON and auto-wraps raw Python into notebook schema if needed.
    - Creates intermediate directories automatically.
    """
    try:
        target = (work_dir / path).resolve()
        # Security: prevent path traversal outside work_dir
        if not str(target).startswith(str(work_dir.resolve())):
            return _err(f"Path '{path}' escapes work_dir — rejected.")

        target.parent.mkdir(parents=True, exist_ok=True)

        # Auto-handle .ipynb: validate JSON or wrap Python code into notebook schema
        if target.suffix.lower() == ".ipynb":
            content = _ensure_valid_notebook(content, path)

        target.write_text(content, encoding="utf-8")
        size = target.stat().st_size
        return _ok(f"Written '{path}' ({size:,} bytes)")
    except Exception as e:
        return _err(str(e))


def _ensure_valid_notebook(content: str, filename: str) -> str:
    """
    Ensures content is a valid Jupyter notebook JSON.
    If it's raw Python (or invalid JSON), wraps it into proper .ipynb structure
    by splitting on '# %%' or '##' section markers into separate cells.
    Works with zero external dependencies (pure standard library json).
    """
    stripped = re.sub(r"```[a-zA-Z]*\n?", "", content).replace("```", "").strip()
    try:
        parsed = json.loads(stripped)
        if isinstance(parsed, dict) and "cells" in parsed and "nbformat" in parsed:
            return json.dumps(parsed, indent=2)
    except Exception:
        pass

    # Not valid notebook JSON — treat as raw Python and split into cells
    sections = re.split(r"\n(?=# %%|## )", content.strip())
    if len(sections) == 1:
        sections = re.split(r"\n{3,}", content.strip())

    name = Path(filename).stem.replace("_", " ").title()
    nb_cells = [
        {
            "cell_type": "markdown",
            "metadata": {},
            "source": [f"# {name}\n\nGenerated by Vicarius Agent."],
        }
    ]

    for section in sections:
        section = section.strip()
        if not section:
            continue
        if section.startswith("# %%") or section.startswith("## "):
            lines = section.splitlines()
            header = lines[0].lstrip("# ").strip()
            body = "\n".join(lines[1:]).strip()
            nb_cells.append({
                "cell_type": "markdown",
                "metadata": {},
                "source": [f"## {header}"],
            })
            if body:
                nb_cells.append({
                    "cell_type": "code",
                    "execution_count": None,
                    "metadata": {},
                    "outputs": [],
                    "source": [body],
                })
        else:
            nb_cells.append({
                "cell_type": "code",
                "execution_count": None,
                "metadata": {},
                "outputs": [],
                "source": [section],
            })

    nb_dict = {
        "cells": nb_cells,
        "metadata": {
            "kernelspec": {
                "display_name": "Python 3",
                "language": "python",
                "name": "python3"
            },
            "language_info": {
                "name": "python",
                "version": "3.10.11"
            }
        },
        "nbformat": 4,
        "nbformat_minor": 5
    }
    return json.dumps(nb_dict, indent=2)


