# ─────────────────────────────────────────────

def tool_search_web(query: str, max_results: int = 3) -> str:
    """
    Run a lightweight web search via DuckDuckGo Instant Answer API.
    Returns relevant snippets for the query.
    Useful for looking up API documentation, function signatures, algorithms.
    """
    try:
        import requests
        url = "https://api.duckduckgo.com/"
        params = {"q": query, "format": "json", "no_html": "1", "skip_disambig": "1"}
        resp = requests.get(url, params=params, timeout=8)
        if not resp.ok:
            return _err(f"Search failed with HTTP {resp.status_code}")
        data = resp.json()
        parts = []
        if data.get("AbstractText"):
            parts.append(data["AbstractText"])
        for r in data.get("RelatedTopics", [])[:max_results]:
            if isinstance(r, dict) and r.get("Text"):
                parts.append(r["Text"])
        if not parts:
            return f"No results found for: {query}"
        return "\n\n".join(parts[:max_results])
    except Exception as e:
        return _err(f"Search error: {e}")


